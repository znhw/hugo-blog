// Function to apply a specific theme
function applyTheme(themeName) {
  // Set the data-theme attribute on the root HTML element
  document.documentElement.setAttribute('data-theme', themeName);
  // Save the user's preference to localStorage
  localStorage.setItem('theme', themeName);
}

// Function to toggle the theme between 'light' and 'dark'
function toggleTheme() {
  const currentTheme = document.documentElement.getAttribute('data-theme');
  const newTheme = currentTheme === 'dark' ? 'light' : 'dark';
  const buttonText = newTheme === 'dark' ? '☀︎' : '⏾';
  document.getElementById('theme-toggle').textContent = buttonText;
  applyTheme(newTheme);
}

// Immediately invoked function to set the theme on initial page load
(function () {
  // Check if a theme is already saved in localStorage
  const savedTheme = localStorage.getItem('theme');
  // Check user's system preference if no theme is saved
  const systemPrefersDark = window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches;
  
  if (savedTheme) {
    // Use the saved theme
    applyTheme(savedTheme);
  } else if (systemPrefersDark) {
    // Or use the system's preference
    applyTheme('dark');
  } else {
    // Default to light theme if no preferences found
    applyTheme('light');
  }
})();

// Add event listener after DOM loads
document.addEventListener("DOMContentLoaded", function () {
  const button = document.getElementById('theme-toggle');

  if (button) {
    button.addEventListener('click', toggleTheme);
  }
});

toggleSocialButtons = function() {
  const shareBtn = document.getElementById('share-icon');
  const socialButtons = document.querySelector('.socialButtons'); 

  socialButtons.style.display = 'none'; // Hide social buttons by default
  
  shareBtn.addEventListener('click', function() {
    console.log('Share button clicked');
    if (socialButtons.style.display === 'flex') {
      socialButtons.style.display = 'none';
    }   else {      socialButtons.style.display = 'flex';   }     
  });
};

document.addEventListener("DOMContentLoaded", toggleSocialButtons);
